-- One login per person for the whole app: customers, employees, partners and Pesaroll staff.
create table users (
    id                 uuid primary key,              -- UUID v7, generated by the app
    email              text unique,
    phone              text unique,
    name               text not null,
    password_hash      text,                          -- null for employees who sign in by code
    email_verified_at  timestamptz,
    phone_verified_at  timestamptz,
    status             text not null default 'active' check (status in ('active', 'locked', 'disabled')),
    created_at         timestamptz not null default now(),
    updated_at         timestamptz not null default now(),
    check (email is not null or phone is not null)
);

-- The app role reads and writes; row-level security decides which rows.
grant select, insert, update, delete on table users to pesaroll_app;
