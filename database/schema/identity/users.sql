-- One login per person for the whole app: customers, employees, partners and Pesaroll staff.
create table users (
    id                   uuid primary key,              -- UUID v7, generated by the app
    email                text unique,                   -- stored lowercase
    phone                text unique,                   -- stored as +254...
    name                 text not null,
    password_hash        text,                          -- null for employees who sign in by code
    signup_role          text check (signup_role in ('owner', 'hr_payroll', 'accountant', 'other')),
    failed_signin_count  integer not null default 0,
    locked_until         timestamptz,
    email_verified_at    timestamptz,
    phone_verified_at    timestamptz,
    status               text not null default 'active' check (status in ('active', 'locked', 'disabled')),
    created_at           timestamptz not null default now(),
    updated_at           timestamptz not null default now(),
    check (email is not null or phone is not null)
);

-- A person sees and changes only their own row. Members of the same organization
-- are visible too: see users_same_org in identity/users_policies.sql (it needs memberships).
alter table users enable row level security;

create policy users_self on users
    using (id = app_user_id());

-- The app role reads and writes; row-level security decides which rows.
grant select, insert, update, delete on table users to pesaroll_app;
