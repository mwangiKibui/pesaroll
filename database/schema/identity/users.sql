-- One login per person for the whole app: customers, employees, partners and Pesaroll staff.
create table users (
    id                   uuid primary key,              -- UUID v7, generated by the app
    email                text unique,                   -- stored lowercase
    phone                text unique,                   -- stored as +254...
    first_name           text not null check (length(btrim(first_name)) between 1 and 60),
    middle_name          text check (middle_name is null or length(btrim(middle_name)) between 1 and 60),
    last_name            text not null check (length(btrim(last_name)) between 1 and 60),
    full_name            text generated always as (
                             first_name || coalesce(' ' || middle_name, '') || ' ' || last_name) stored,
    password_hash        text,                          -- null for employees who sign in by code
    signup_role_id       uuid references signup_roles (id),     -- picked from the list at sign-up
    signup_role_other    text check (signup_role_other is null
                                     or length(btrim(signup_role_other)) between 1 and 80),
    failed_signin_count  integer not null default 0,
    locked_until         timestamptz,
    email_verified_at    timestamptz,
    phone_verified_at    timestamptz,
    status               text not null default 'active' check (status in ('active', 'locked', 'disabled')),
    -- How the account came in. Only 'self' (the sign-up page) onboards an organization (ONB-02);
    -- invitations (AUTH-08), the back office (BO-03) and partners (PRN-01) set theirs.
    signed_up_via        text not null default 'self' check (signed_up_via in ('self', 'invitation', 'back_office', 'partner')),
    created_at           timestamptz not null default now(),
    updated_at           timestamptz not null default now(),
    check (email is not null or phone is not null)
);

-- A person sees and changes only their own row. Members of the same organization
-- are visible too: see users_same_org in identity/users_policies.sql (it needs memberships).
alter table users enable row level security;

create policy users_self on users
    using (id = app_user_id());

-- The app role reads and writes; row-level security decides which rows.
grant select, insert, update, delete on table users to pesaroll_app;
